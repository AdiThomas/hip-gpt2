#!/usr/bin/env python3
"""Generate src/io/unicode_tables.inc: sorted code-point ranges for \\p{L}, \\p{N} and \\s.

Classes are computed by brute force over all code points (surrogates excluded) with the
installed `regex` module -- the same engine encoder.py uses -- so the C++ tokenizer's
pre-tokenizer classes match it exactly. Output is deterministic for a given regex version.
"""
import argparse
import os
import sys
import unicodedata

import regex


def ranges(pred):
    out, start, prev = [], None, None
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            ok = False
        else:
            ok = pred(chr(cp))
        if ok:
            if start is None:
                start = cp
            prev = cp
        elif start is not None:
            out.append((start, prev))
            start = None
    if start is not None:
        out.append((start, prev))
    return out


def emit(name, rs):
    lines = ["static const uint32_t %s[][2] = {" % name]
    row = []
    for a, b in rs:
        row.append("{0x%X,0x%X}," % (a, b))
        if len(row) == 6:
            lines.append("    " + " ".join(row))
            row = []
    if row:
        lines.append("    " + " ".join(row))
    lines.append("};")
    lines.append("static const size_t %sCount = sizeof(%s) / sizeof(%s[0]);" % (name, name, name))
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "..",
                                                  "src", "io", "unicode_tables.inc"))
    args = ap.parse_args()
    pl, pn, ps = regex.compile(r"\p{L}"), regex.compile(r"\p{N}"), regex.compile(r"\s")
    L = ranges(lambda c: pl.fullmatch(c) is not None)
    N = ranges(lambda c: pn.fullmatch(c) is not None)
    S = ranges(lambda c: ps.fullmatch(c) is not None)
    text = "// GENERATED by tools/gen_unicode_tables.py -- do not edit.\n"
    text += "// regex module %s, unicodedata (Python) Unicode %s. Surrogates excluded.\n" % (
        regex.__version__, unicodedata.unidata_version)
    text += "// Included by tokenizer.cpp only. Ranges are inclusive and sorted.\n"
    text += emit("kUniLetter", L) + "\n" + emit("kUniNumber", N) + "\n" + emit("kUniSpace", S) + "\n"
    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote %s (L=%d ranges, N=%d, S=%d)" % (args.out, len(L), len(N), len(S)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
