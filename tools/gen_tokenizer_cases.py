    "win\r\nbreak", "a\n\n\nb", "\n\n\n", "   ", "\n", " \n ", "\r\n", " ", "  ", "\t", " \t \n\t ",
    "x \n", "x \n\ny", "word   \n  next",
    "I'm, you're, he's, we've, they'll, I'd, don't", "DON'T I'M YOU'RE HE'S WE'VE THEY'LL I'D",
    "1234567890 3.14159 1,000,000 2026-11-16", "!!!??? ... --- (a) [b] {c}",
    "<|endoftext|>", "text <|endoftext|> more", "'s't're", "''''", "'s", "'re", "'ll", "'x", "' s", "it's's",
    "foo_bar __init__ camelCase", "naïve café résumé", "日本語のテキスト 中文 한국어",
    "emoji \U0001F44D\U0001F3FD thumbs", "family \U0001F468‍\U0001F469‍\U0001F467‍\U0001F466 here",
    "flag \U0001F1E8\U0001F1E6 and \U0001F1EF\U0001F1F5", "\U0001F600",
    "nbsp here", "em space", "ideographic　space", "  lead", "end ",
    "a  b", "　　x", "x  y", " line sep para",
    "x²+y³=½ ①②③ ٣", "١٢٣ १२", "ⅠⅡ roman",
    "é́ combining", "مرحبا שלום", "สวัสดี",
    "café’s", "“quoted” — dash", "e.g. i.e. U.S.A.", "$100.50 50% #hash @user",
    "https://example.com/path?q=1&r=2", "a+b=c; d*e/f\\g|h", "snake_case_name2 CONSTANT_NAME",
    "\x00\x01\x02 ctrl", "del\x7f char", "\x1c\x1d\x1e\x1f", "ZERO​WIDTH", "bom﻿here",
    "supplementary \U00020000\U00020001 ideographs", "\U0001D400\U0001D401 math bold", "\U0010FFFF",
    "The quick brown fox jumps over the lazy dog.",
